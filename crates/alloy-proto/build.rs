//! Compiles the definitions under `proto/` into Rust (ARFC 0008 clause 3.10).
//!
//! `protox` parses and checks the definitions in Rust, so the build runs no
//! `protoc` and reaches no network. Before generating anything the script
//! fails the build on any message, field, enum, enum value, service, or method
//! that has no leading comment (ARFC 0008 clause 3.11).

use std::env;
use std::path::PathBuf;

use protox::prost_reflect::prost_types::{FileDescriptorProto, FileDescriptorSet};

/// The definition files, relative to the `proto/` root.
const FILES: [&str; 3] = [
    "alloy/common/errors.proto",
    "alloy/cluster/v1alpha1/cluster.proto",
    "alloy/iam/v1alpha1/iam.proto",
];

// `FileDescriptorProto` field numbers that a source location path names
// (descriptor.proto).
const FILE_MESSAGE: i32 = 4;
const FILE_ENUM: i32 = 5;
const FILE_SERVICE: i32 = 6;
const MESSAGE_FIELD: i32 = 2;
const MESSAGE_NESTED: i32 = 3;
const MESSAGE_ENUM: i32 = 4;
const ENUM_VALUE: i32 = 2;
const SERVICE_METHOD: i32 = 2;

fn main() {
    if let Err(message) = run() {
        // A build script reports failure by its exit status; `panic!` prints
        // the reason and exits non-zero.
        panic!("{message}");
    }
}

fn run() -> Result<(), String> {
    let manifest = env::var("CARGO_MANIFEST_DIR").map_err(|e| e.to_string())?;
    let root = PathBuf::from(manifest).join("../../proto");
    println!("cargo:rerun-if-changed={}", root.display());
    let fds = protox::Compiler::new([&root])
        .map_err(|e| e.to_string())?
        .include_source_info(true)
        .include_imports(true)
        .open_files(FILES)
        .map_err(|e| e.to_string())?
        .file_descriptor_set();
    let missing = undocumented(&fds);
    if !missing.is_empty() {
        return Err(format!(
            "undocumented items in proto/ (ARFC 0008 clause 3.11):\n  {}",
            missing.join("\n  ")
        ));
    }
    tonic_prost_build::configure()
        .build_client(true)
        .build_server(true)
        .compile_well_known_types(false)
        .compile_fds(fds)
        .map_err(|e| e.to_string())
}

/// Every item of an Alloy file with no leading comment, as `<file>: <name>`.
fn undocumented(fds: &FileDescriptorSet) -> Vec<String> {
    let mut missing = Vec::new();
    for file in fds.file.iter().filter(|f| f.name().starts_with("alloy/")) {
        let documented: Vec<&[i32]> = file
            .source_code_info
            .iter()
            .flat_map(|info| &info.location)
            .filter(|l| !l.leading_comments().trim().is_empty())
            .map(|l| l.path.as_slice())
            .collect();
        let mut check = |path: Vec<i32>, name: &str| {
            if !documented.contains(&path.as_slice()) {
                missing.push(format!("{}: {name}", file.name()));
            }
        };
        items(file, &mut check);
    }
    missing
}

/// Calls `check` with the source path and name of every item of `file`.
fn items(file: &FileDescriptorProto, check: &mut impl FnMut(Vec<i32>, &str)) {
    for (i, message) in file.message_type.iter().enumerate() {
        message_items(vec![FILE_MESSAGE, index(i)], message, check);
    }
    for (i, e) in file.enum_type.iter().enumerate() {
        enum_items(vec![FILE_ENUM, index(i)], e, check);
    }
    for (i, service) in file.service.iter().enumerate() {
        let path = vec![FILE_SERVICE, index(i)];
        check(path.clone(), service.name());
        for (j, method) in service.method.iter().enumerate() {
            let mut p = path.clone();
            p.extend([SERVICE_METHOD, index(j)]);
            check(p, &format!("{}.{}", service.name(), method.name()));
        }
    }
}

fn message_items(
    path: Vec<i32>,
    message: &protox::prost_reflect::prost_types::DescriptorProto,
    check: &mut impl FnMut(Vec<i32>, &str),
) {
    // A map field's entry type is generated by the compiler and has no source.
    if message.options.as_ref().is_some_and(|o| o.map_entry()) {
        return;
    }
    check(path.clone(), message.name());
    for (i, field) in message.field.iter().enumerate() {
        let mut p = path.clone();
        p.extend([MESSAGE_FIELD, index(i)]);
        check(p, &format!("{}.{}", message.name(), field.name()));
    }
    for (i, nested) in message.nested_type.iter().enumerate() {
        let mut p = path.clone();
        p.extend([MESSAGE_NESTED, index(i)]);
        message_items(p, nested, check);
    }
    for (i, e) in message.enum_type.iter().enumerate() {
        let mut p = path.clone();
        p.extend([MESSAGE_ENUM, index(i)]);
        enum_items(p, e, check);
    }
}

fn enum_items(
    path: Vec<i32>,
    e: &protox::prost_reflect::prost_types::EnumDescriptorProto,
    check: &mut impl FnMut(Vec<i32>, &str),
) {
    check(path.clone(), e.name());
    for (i, value) in e.value.iter().enumerate() {
        let mut p = path.clone();
        p.extend([ENUM_VALUE, index(i)]);
        check(p, &format!("{}.{}", e.name(), value.name()));
    }
}

/// A descriptor index as a path element. A file has far fewer than 2^31 items.
fn index(i: usize) -> i32 {
    i32::try_from(i).unwrap_or(i32::MAX)
}
