//! The Protocol Buffers definitions of the native API and their generated
//! Rust code (ARFC 0008 sections 2 and 3).
//!
//! The definitions live under `proto/alloy/` at the repository root; the build
//! compiles them with `prost` and `tonic` and fails on any item without
//! documentation (ARFC 0008 clause 3.11). Each package is a module here:
//!
//! - [`common::v1alpha1`]: the [`Error`](common::v1alpha1::Error) of every
//!   method and its [`ErrorCode`](common::v1alpha1::ErrorCode)s (clause 3.6).
//! - [`cluster::v1alpha1`]: the `cluster` service, with the kind `Node`
//!   (clause 3.13), its generated client
//!   ([`ClusterServiceClient`](cluster::v1alpha1::cluster_service_client::ClusterServiceClient))
//!   and server
//!   ([`ClusterServiceServer`](cluster::v1alpha1::cluster_service_server::ClusterServiceServer)).
//!
//! [`error`] maps an error to and from a gRPC status with the trailer
//! `alloy-error-bin`, and each code to its gRPC status, HTTP status, and CLI
//! exit code.

#![forbid(unsafe_code)]

pub mod error;

/// Package `alloy.common`.
pub mod common {
    /// Package `alloy.common.v1alpha1`: the error of every method.
    pub mod v1alpha1 {
        include!(concat!(env!("OUT_DIR"), "/alloy.common.v1alpha1.rs"));
    }
}

/// Package `alloy.cluster`.
pub mod cluster {
    /// Package `alloy.cluster.v1alpha1`: the `cluster` service.
    #[allow(
        clippy::allow_attributes_without_reason,
        unused_qualifications,
        reason = "generated by tonic, which names items by full path and gives its own lint attributes no reason"
    )]
    pub mod v1alpha1 {
        include!(concat!(env!("OUT_DIR"), "/alloy.cluster.v1alpha1.rs"));
    }
}
